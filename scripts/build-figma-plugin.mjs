#!/usr/bin/env node
/**
 * Bundles figma-plugin/src/plugin.js + tokens.json → figma-plugin/code.js (a single file, as Figma requires).
 *   node scripts/build-figma-plugin.mjs          write code.js
 *   node scripts/build-figma-plugin.mjs --check  fail if code.js is stale (tokens changed, plugin not rebuilt)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'src/design-system/tokens/tokens.json'), 'utf8'));
const source = readFileSync(resolve(root, 'figma-plugin/src/plugin.js'), 'utf8').replace(/\r\n/g, '\n').replace(/^\/\/ @ts-check\n/, '');
const out = resolve(root, 'figma-plugin/code.js');

const code = `// AUTO-GENERATED by scripts/build-figma-plugin.mjs. Edit figma-plugin/src/plugin.js and tokens.json instead.
const GW_TOKENS = ${JSON.stringify(tokens)};
${source}`;

const current = existsSync(out) ? readFileSync(out, 'utf8').replace(/\r\n/g, '\n') : '';
if (process.argv.includes('--check')) {
  if (current !== code) {
    console.error('✗ figma-plugin/code.js is out of date. Run "npm run figma:build".');
    process.exit(1);
  }
  console.log('✓ Figma plugin is up to date with tokens.json');
} else if (current !== code) {
  writeFileSync(out, code);
  console.log('✓ wrote figma-plugin/code.js');
} else {
  console.log('✓ figma-plugin/code.js already up to date');
}
